import assert from 'node:assert/strict';
import { HOME_LAYOUT_KEY, readHomeLayout, saveHomeLayout } from '../js/home-layout.js';
const records=new Map();let fail=false;
globalThis.localStorage={getItem:key=>records.get(key)??null,setItem:(key,value)=>{if(fail)throw Error('full');records.set(key,value);}};
globalThis.window=new EventTarget();
const scope={semester:'2026-2027-1',className:'测试班'};
assert.deepEqual(readHomeLayout(scope),{order:['items','courses'],expanded:{items:false,courses:true}});
records.set('course-dashboard-personal-items-v1','untouched-records');
saveHomeLayout(scope,{order:['courses','items']});
saveHomeLayout(scope,{expanded:{courses:false}});
assert.deepEqual(readHomeLayout(scope),{order:['courses','items'],expanded:{items:false,courses:false}});
saveHomeLayout(scope,{expanded:{items:true}});
assert.equal(readHomeLayout(scope).expanded.courses,false,'folding one module never changes the other');
assert.equal(readHomeLayout({...scope,className:'另一个班'}).order[0],'items');
assert.equal(readHomeLayout({...scope,semester:'另一学期'}).expanded.items,false);
assert.equal(records.get('course-dashboard-personal-items-v1'),'untouched-records','module changes never overwrite item ordering/data');
const before=records.get(HOME_LAYOUT_KEY);fail=true;
assert.throws(()=>saveHomeLayout(scope,{order:['items','courses']}),/保存失败/);fail=false;
assert.equal(records.get(HOME_LAYOUT_KEY),before);
assert.throws(()=>saveHomeLayout(scope,{order:['items','items']}),/无效/);
assert.equal(records.get(HOME_LAYOUT_KEY),before);
records.set(HOME_LAYOUT_KEY,'{bad');
assert.throws(()=>readHomeLayout(scope),/原内容已保留/);
assert.throws(()=>saveHomeLayout(scope,{expanded:{items:false}}),/原内容已保留/);
assert.equal(records.get(HOME_LAYOUT_KEY),'{bad');
console.log('Home layout: one-item defaults, independent expansion, module order, scope isolation, item preservation and failed/corrupt storage passed.');
