import assert from 'node:assert/strict';
import { resolveDateExpression as date, resolveTimeExpression as time, resolveSections, resolveNoticeItems, describeTimeContext, noticeRecordFields } from '../js/notice-model.js';
import { getCourseSegments } from '../js/time.js';
process.env.TZ='Asia/Shanghai';
const referenceAt='2026-10-21T12:00:00+08:00';
assert.equal(date('明天',referenceAt).date,'2026-10-22');
assert.equal(date('下周一',referenceAt).date,'2026-10-26');
assert.equal(date('明晚',referenceAt).date,'2026-10-22');
assert.equal(date('周一',referenceAt).date,'2026-10-26');
assert.deepEqual(date('下周',referenceAt).range,{from:'2026-10-26',through:'2026-11-01'});
assert.ok(date('2026年10月22日周五',referenceAt).issues.length);
assert.ok(date('2026-02-30',referenceAt).issues.length);
assert.equal(time('明晚八点半').time,'20:30');
assert.equal(time('下午3点一刻').time,'15:15');
assert.equal(time('08:45').time,'08:45');
assert.equal(time('三点').time,'');assert.ok(time('三点').issues.length);
assert.deepEqual(resolveSections('第三四节'),{start:3,end:4});
assert.deepEqual(resolveSections('第3—4节'),{start:3,end:4});
const sectionTimes={winter:{'1':{start:'08:00',end:'08:45'},'2':{start:'08:55',end:'09:40'},'3':{start:'10:00',end:'10:45'},'4':{start:'10:55',end:'11:40'}}};
const seasonRule={winter:'10-01_to_05-31'};
const course={date:'2026-10-22',courseName:'大学英语',season:'winter',startSection:1,endSection:2,startTime:'08:00',endTime:'09:40',startDateTime:new Date('2026-10-22T08:00'),endDateTime:new Date('2026-10-22T09:40')};
course.segments=getCourseSegments(course,sectionTimes);
const options={referenceAt,courses:[course],sectionTimes,seasonRule};
const base={kind:'task',title:'作业',dateExpression:null,startExpression:null,endExpression:null,deadlineExpression:null,sectionExpression:null,courseHint:null,location:null,relation:'unspecified',relationEvidence:null};
let text='下次英语课前交作业';
let result=resolveNoticeItems([{...base,courseHint:'英语',relation:'before_next_class',relationEvidence:'下次英语课前'}],{...options,text})[0];
assert.equal(result.date,'2026-10-22');assert.equal(result.dueTime,'08:00');assert.equal(result.courseName,'大学英语');assert.equal(result.needsConfirmation,false);
assert.match(result.timeContext,/第1节/);
text='明天二三节课间去教学楼甲';
result=resolveNoticeItems([{...base,kind:'activity',dateExpression:'明天',sectionExpression:'二三节课间',relation:'between_sections',location:'教学楼甲'}],{...options,text})[0];
assert.equal(result.startTime,'09:40');assert.equal(result.endTime,'10:00');assert.equal(result.location,'教学楼甲');assert.equal(result.needsConfirmation,false);
assert.match(describeTimeContext('2026-10-22','08:50',[course],sectionTimes,seasonRule),/课间/);
text='明天下午三点交作业';
result=resolveNoticeItems([{...base,dateExpression:'明天',deadlineExpression:'下午三点'}],{...options,text})[0];
assert.equal(result.dueTime,'15:00');assert.match(result.timeContext,/未排课/);
text='下周交作业';result=resolveNoticeItems([{...base,dateExpression:'下周'}],{...options,text})[0];
assert.equal(result.date,'');assert.match(result.timeContext,/周范围/);
text='三点交';result=resolveNoticeItems([{...base,deadlineExpression:'三点'}],{...options,text})[0];assert.equal(result.dueTime,'');assert.equal(result.needsConfirmation,true);
text='想到一个好点子';result=resolveNoticeItems([{...base,kind:'note'}],{...options,text})[0];assert.equal(result.needsConfirmation,false,'optional date/location absence is not uncertainty');
text='下次课前交';result=resolveNoticeItems([{...base,relation:'before_next_class',relationEvidence:'下次课前'}],{...options,text})[0];assert.ok(result.issues.length,'unknown course never borrows arbitrary current class');
console.log('通知换算：相对日期、星期冲突、中文时刻、真实小节与课间、下次课、可选字段及歧义检查通过。');
let fields=noticeRecordFields({kind:'activity',date:'2026-10-22',startTime:'15:00',endTime:'16:00',dueTime:'',timeContext:'15:00—16:00',needsConfirmation:false});
assert.equal(fields.dueTime,'15:00','an activity uses its starting time for the concrete-time field');
assert.equal(fields.windowStart,'15:00');assert.equal(fields.windowEnd,'16:00');
fields=noticeRecordFields({kind:'task',date:'2026-10-22',startTime:'10:00',endTime:'11:40',dueTime:'',needsConfirmation:false});
assert.equal(fields.dueTime,'','a task period must not be turned into a made-up deadline');assert.equal(fields.windowStart,'10:00');
fields=noticeRecordFields({kind:'task',date:'2026-10-22',startTime:'10:00',endTime:'11:40',dueTime:'18:00',needsConfirmation:false});
assert.equal(fields.dueTime,'18:00','an explicit deadline takes precedence over a related period');
fields=noticeRecordFields({kind:'activity',date:'',startTime:'15:00',endTime:'16:00',dueTime:'',needsConfirmation:true});
assert.equal(fields.dueTime,'');assert.equal(fields.windowStart,'15:00');assert.match(fields.timeContext,/日期未定/,'a missing date cannot silently discard the known clock time');
console.log('应用映射：活动开始、明确截止、相关小节区间、未定日期的时刻保留检查通过。');
