import assert from 'node:assert/strict';
import * as store from '../js/daily-store.js';
import { outfitRecommendation, buildAdvice, chooseAdvice, departurePlan, nextDate } from '../js/daily-model.js';

const memory = new Map();
let failWrite = false;
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => { if (failWrite) throw Error('quota'); memory.set(key, value); } };
globalThis.window = new EventTarget();
const group = (category, quantity = 1, state = 'ready', needsBelt = 'no') => ({ category, quantity, state, needsBelt, color: 'unknown', name: '' });
const day = '2026-11-09';
const course = (date, name, location = '') => ({ date, courseName: name, location, startTime: '08:00', startDateTime: new Date(`${date}T08:00:00`), endDateTime: new Date(`${date}T09:40:00`) });
assert.equal(store.readDailyData().garments.length, 0);
assert.equal(store.addGarments([group('tshirt'), group('sportshorts', 2), group('joggers'), group('jeans', 1, 'ready', 'yes')]), 5);
let data = store.readDailyData();
const shorts = data.garments.filter(item => item.category === 'sportshorts');
assert.notEqual(shorts[0].id, shorts[1].id, 'identical garments have physical identities');
const top = data.garments.find(item => item.category === 'tshirt');
const jeans = data.garments.find(item => item.category === 'jeans');
const joggers = data.garments.find(item => item.category === 'joggers');
store.saveDailyProfile({ peNeedsShorts: true, refreshPerMinute: 2, laundryEveryDays: 3 });
store.changeGarmentState([shorts[0].id], 'dirty');
store.changeGarmentState([shorts[1].id], 'drying', day);
data = store.readDailyData();
let fit = outfitRecommendation(data, day, [course(day, '体育与健康')]);
assert.equal(fit.readyShorts, 0, 'expected ready date never implies dry confirmation');
assert.equal(fit.sets.length, 0, 'PE shorts requirement cannot silently fall back to trousers');
assert.match(fit.missing.join(''), /短裤/);
const washed = data.lastLaundryAt;
assert.ok(washed);
store.changeGarmentState([shorts[1].id], 'ready');
assert.equal(store.readDailyData().lastLaundryAt, washed, 'collecting clothes does not rewrite last wash time');
fit = outfitRecommendation(store.readDailyData(), day, [course(day, '体育')]);
assert.equal(fit.sets[0].pieces.find(item => item.category === 'sportshorts').id, shorts[1].id);
assert.ok(fit.sets[0].pieces.every(item => item.state === 'ready'));
store.changeGarmentState([shorts[1].id], 'dirty');
store.changeGarmentState([joggers.id], 'dirty');
fit = outfitRecommendation(store.readDailyData(), day, []);
assert.equal(fit.sets.length, 0, 'required belt cannot be silently omitted');
assert.match(fit.missing.join(''), /腰带/);
store.addGarments([group('belt')]);
fit = outfitRecommendation(store.readDailyData(), day, []);
assert.ok(fit.sets[0].pieces.some(item => item.category === 'belt'));
store.saveOutfit('常用组合', [top.id, jeans.id]);
assert.equal(store.readDailyData().outfits.length, 1);
assert.throws(() => store.saveOutfit('重复下装', [top.id, jeans.id, joggers.id]));
store.setArchived('garment', jeans.id, true);
assert.equal(outfitRecommendation(store.readDailyData(), day, []).sets.length, 0);
store.setArchived('garment', jeans.id, false);
assert.ok(outfitRecommendation(store.readDailyData(), day, []).sets.length);
store.changeGarmentState([joggers.id], 'ready');
store.changeGarmentState([shorts[1].id], 'ready');
store.saveRunPlan(day, true);
fit = outfitRecommendation(store.readDailyData(), day, [], [course(nextDate(day), '体育')]);
assert.ok(fit.sets[0].pieces.some(item => item.id === joggers.id), 'reserve scarce shorts by offering running trousers');

store.addGarments([group('belt'), group('shoes'), group('trainers')]);
data = store.readDailyData();
const secondBelt = data.garments.filter(item => item.category === 'belt')[1];
const casualShoes = data.garments.find(item => item.category === 'shoes');
store.saveOutfit('另一条腰带', [top.id, jeans.id, secondBelt.id]);
const beltData = store.readDailyData();
beltData.outfits = beltData.outfits.filter(outfit => outfit.name === '另一条腰带');
fit = outfitRecommendation(beltData, nextDate(day), []);
const jeansSet = fit.sets.find(set => set.pieces.some(item => item.id === jeans.id));
assert.equal(jeansSet.pieces.filter(item => item.category === 'belt').length, 1, 'saved required belt is not duplicated');
assert.ok(jeansSet.pieces.some(item => item.id === secondBelt.id), 'saved belt choice is retained');
store.saveOutfit('休闲鞋组合', [top.id, joggers.id, casualShoes.id]);
store.saveOutfit('短裤常用组合', [top.id, shorts[1].id]);
fit = outfitRecommendation(store.readDailyData(), day, [], [course(nextDate(day), '体育')]);
assert.ok(fit.sets[0].pieces.some(item => item.id === joggers.id), 'upcoming shorts need takes priority over favorite shorts');
assert.ok(fit.sets[0].pieces.some(item => item.category === 'trainers'), 'unsuitable saved shoes fall back to available sports shoes');

const profile = { ...store.DEFAULT_PROFILE, baseArea: '常用出发区', destinationKeyword: '教学楼A', destinationArea: '目标区域', travelMinutes: 18, breakfastMode: 'onway', breakfastBuyMinutes: 6, breakfastEatMinutes: 12 };
const target = course(day, '课程', '教学楼A101');
assert.equal(departurePlan(target, profile).clock, '07:36', 'eating on route overlaps travel; buying is extra');
assert.equal(departurePlan(target, { ...profile, breakfastMode: 'sit' }).clock, '07:24');
assert.equal(departurePlan(target, { ...profile, breakfastMode: 'prepared' }).clock, '07:42');
assert.equal(departurePlan(target, profile, { location: '目标区域另一教学楼' }), null, 'already in destination area avoids duplicate cross-area advice');

const now = new Date(`${day}T12:00:00`);
const item = { id: 'test-task', kind: 'task', text: '<img src=x>作业', nextStep: '', dueDate: day, dueTime: '20:00', completedAt: '', deletedAt: '', needsConfirmation: false };
const input = { now, courses: [], tomorrowCourses: [], items: [item], data: store.readDailyData() };
let advice = buildAdvice(input);
assert.ok(advice[0].id.startsWith('item:'));
assert.ok(!buildAdvice({ ...input, items: [{ ...item, needsConfirmation: true }] }).some(item => item.id.startsWith('item:')));
assert.ok(!buildAdvice({ ...input, items: [{ ...item, completedAt: now.toISOString() }] }).some(item => item.id.startsWith('item:')));
const late = buildAdvice({ ...input, now: new Date(`${day}T23:59:30`), items: [{ ...item, dueTime: '' }] });
assert.doesNotMatch(late[0].lines.join(''), /所设时间已过/, 'date-only reminder stays on its day');
const original = chooseAdvice(advice, 'scope', now, 2);
assert.equal(chooseAdvice(advice, 'scope', now, 2).line, original.line, 'same date/context reuses wording');
assert.notEqual(chooseAdvice(advice, 'scope', now, 2, true).line, original.line);
assert.ok(chooseAdvice(advice, 'scope', now, 2, true).id.startsWith('item:'), 'refresh cannot hide urgent facts');
assert.equal(chooseAdvice(advice, 'scope', now, 2, true).limited, true);
assert.notEqual(chooseAdvice(advice, 'scope', new Date(+now + 60001), 2, true).limited, true);

const backup = structuredClone(store.readDailyData());
store.mergeDailyBackup(backup);
assert.equal(store.readDailyData().garments.length, backup.garments.length, 'reimport is idempotent');
const before = memory.get(store.DAILY_KEY);
assert.throws(() => store.changeGarmentState([shorts[0].id], 'drying', '2026-02-30'));
assert.equal(memory.get(store.DAILY_KEY), before);
failWrite = true;
assert.throws(() => store.saveDailyProfile({ city: '测试地区' }), /保存失败/);
assert.equal(memory.get(store.DAILY_KEY), before);
failWrite = false;
memory.set(store.DAILY_KEY, '{broken');
assert.throws(() => store.readDailyData(), /原内容已保留/);
assert.throws(() => store.addGarments([group('tshirt')]));
assert.throws(() => store.mergeDailyBackup(backup));
assert.equal(memory.get(store.DAILY_KEY), '{broken');
store.mergeDailyBackup(backup, true);
assert.equal(store.readDailyData().garments.length, backup.garments.length);
console.log('Daily assistant: identities, wash states, PE/run/belts, departure/breakfast, confirmed deadlines, refresh quotas, backup merge and failed-write preservation passed.');
