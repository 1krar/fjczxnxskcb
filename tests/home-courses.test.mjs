import assert from 'node:assert/strict';
import { getUpcomingCourseGroups,courseKey } from '../js/day-plan.js';
import { courseListCount, courseContinuation, renderUpcomingCourses } from '../js/home-courses.js';
process.env.TZ='Asia/Shanghai';
const at=time=>new Date(`2026-10-23T${time}:00+08:00`);
const segment=(kind,start,end,section)=>({kind,start:at(start),end:at(end),startTime:start,endTime:end,section,nextSection:section});
const course=(name,start,end,section,location)=>({courseName:name,date:'2026-10-23',location,startTime:start,endTime:end,startSection:section,endSection:section+1,startDateTime:at(start),endDateTime:at(end),segments:[]});
const first=course('同名课程','08:00','09:40',1,'北区A101');
first.segments=[segment('lesson','08:00','08:45',1),segment('break','08:45','08:55',2),segment('lesson','08:55','09:40',2)];
const second=course('同名课程','10:00','11:40',3,'南区B201');
second.segments=[segment('lesson','10:00','10:45',3),segment('break','10:45','10:55',4),segment('lesson','10:55','11:40',4)];
const third=course('长名称课程<不执行脚本>','14:00','15:40',5,'教学楼C302');
third.segments=[segment('lesson','14:00','14:45',5),segment('break','14:45','14:55',6),segment('lesson','14:55','15:40',6)];
const courses=[third,second,first];
for(const time of ['07:30','08:00','08:45','08:55']) {
  const value=getUpcomingCourseGroups(courses,at(time));
  assert.equal(value.focus,first);
  assert.deepEqual(value.groups.map(row=>row.course),[second,third],'group by occurrence and actual time; do not merge matching names');
  assert.equal(value.lessonCount,4);
}
assert.deepEqual(getUpcomingCourseGroups(courses,at('08:45')).pending.map(row=>row.section),[2]);
assert.match(courseContinuation(first,first.segments[0],at('08:20')),/08:55继续第2小节.*09:40本次课结束/);
assert.equal(courseContinuation(first,first.segments[2],at('09:00')),'09:40本次课结束');
assert.equal(getUpcomingCourseGroups(courses,at('09:40')).focus,second);
assert.deepEqual(getUpcomingCourseGroups(courses,at('09:40')).groups.map(row=>row.course),[third]);
assert.equal(getUpcomingCourseGroups(courses,at('15:40')).groups.length,0);
assert.equal(getUpcomingCourseGroups(courses,at('15:40')).past.length,3);
const unknown={courseName:'未知时间',location:'教学楼D',segments:[]};
let value=getUpcomingCourseGroups([...courses,unknown],at('08:20'));
assert.equal(value.unknownCount,1);assert.equal(value.lessonCount,4);
assert.equal(value.groups.at(-1).course,unknown,'incomplete timing is retained without treating it as finished');
assert.equal(getUpcomingCourseGroups([unknown],at('08:20')).focus,unknown,'a single unknown course remains in the main card');
const legacy={...third};delete legacy.segments;
assert.equal(getUpcomingCourseGroups([first,legacy],at('07:30')).lessonCount,2);
const state={settings:{showFullLocation:true,showTeacher:true}};
const html=renderUpcomingCourses(courses,at('08:20'),state);
assert.equal((html.match(/class="upcoming-course"/g)||[]).length,2,'two remaining courses produce two rows, not four small lessons plus breaks');
assert.ok(!html.includes('北区A101'),'current occurrence is not duplicated');
assert.match(html,/08:55|10:55/,'actual internal lesson times stay in expandable details');
assert.match(html,/长名称课程&lt;不执行脚本&gt;/);
assert.equal(courseListCount(courses,at('08:20')),'2次 · 4小节');
const folded=renderUpcomingCourses(courses,at('08:20'),state,false);
assert.match(folded,/另有1次课/);assert.equal((folded.match(/data-course-detail="[^"]+" hidden/g)||[]).length,1);
assert.match(renderUpcomingCourses(courses,at('08:20'),state,true,new Set([courseKey(second)])),/data-course-detail="[^"]+" open/);
assert.equal(getUpcomingCourseGroups(courses,at('12:30')).gaps.length,0,'the active midday gap stays in the main card');
console.log('Compact courses: occurrence grouping, focus uniqueness, small-lesson boundaries, unknown timing, counts, history, collapse, details and escaped text passed.');
