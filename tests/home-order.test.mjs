import assert from 'node:assert/strict';
import { sortHomeItems,saveHomeOrder,saveItem,readItems,updateItemState,validateBackup } from '../js/tasks-store.js';
process.env.TZ='Asia/Shanghai';
const memory=new Map();let failWrite=false;
globalThis.localStorage={getItem:key=>memory.get(key)??null,setItem:(key,value)=>{if(failWrite)throw Error('quota');memory.set(key,value);}};
globalThis.window=new EventTarget();
const scope={semester:'2026-2027-1',className:'测试班'};
const fields={...scope,text:'测试事项',title:'',timeRole:'',courseName:'',nextStep:'',kind:'task',source:'other',dueDate:'',dueTime:'',needsConfirmation:false};
const old=saveItem({...fields,title:'旧日期',dueDate:'2026-09-01'});
const far=saveItem({...fields,title:'较远安排',dueDate:'2026-10-24',dueTime:'08:00'});
const later=saveItem({...fields,title:'当天稍后',dueDate:'2026-10-21',dueTime:'17:00'});
const near=saveItem({...fields,title:'即将到来',dueDate:'2026-10-21',dueTime:'15:40'});
const recent=saveItem({...fields,title:'刚过时间',dueDate:'2026-10-21',dueTime:'14:40'});
const undated=saveItem({...fields,title:'日期未定',dueTime:'15:10'});
const another=saveItem({...fields,className:'另一个班',title:'别班'});
const now=new Date('2026-10-21T15:00:00');
const items=readItems().filter(item=>item.className===scope.className);
assert.deepEqual(sortHomeItems(items,now).map(item=>item.id),[near.id,later.id,far.id,recent.id,old.id,undated.id]);
assert.deepEqual(sortHomeItems(items,new Date('2026-10-21T16:00:00')).map(item=>item.id),[later.id,far.id,near.id,recent.id,old.id,undated.id]);
saveHomeOrder(scope,[undated.id,near.id,later.id,far.id,recent.id,old.id]);
let saved=readItems();assert.equal(saved.find(item=>item.id===another.id).homeOrder,null);
assert.equal(sortHomeItems(saved.filter(item=>item.className===scope.className),now)[0].id,undated.id);
saveItem({...near,text:'改一下内容'},near.id);assert.equal(readItems().find(item=>item.id===near.id).homeOrder,1,'editing preserves manual order');
const backup=validateBackup({schemaVersion:1,items:readItems()});assert.equal(backup.items.find(item=>item.id===undated.id).homeOrder,0);
updateItemState(undated.id,'complete');saveHomeOrder(scope,[near.id,later.id]);updateItemState(undated.id,'reopen');
assert.equal(readItems().find(item=>item.id===undated.id).text,'测试事项');
const before=JSON.stringify(readItems());failWrite=true;assert.throws(()=>saveHomeOrder(scope,[old.id,near.id]));failWrite=false;
assert.equal(JSON.stringify(readItems()),before,'failed writes leave notes and order intact');
assert.throws(()=>saveHomeOrder(scope,[near.id,near.id]));
saveHomeOrder(scope);assert.ok(readItems().filter(item=>item.className===scope.className).every(item=>item.homeOrder===null));
assert.equal(sortHomeItems(readItems().filter(item=>item.className===scope.className),now)[0].id,near.id);
console.log('首页排序：临近时间、已过时间、未知日期、手动持久化、编辑与备份、作用域和失败保留通过。');
