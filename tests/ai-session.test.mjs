import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { handleSession, SESSION_COOKIE, SESSION_MS, REMEMBER_MS } from '../server/ai-session.js';
import { handleAI } from '../server/ai-service.js';

const db=new DatabaseSync(':memory:');
const binding={prepare(sql){const state={args:[]};return {bind(...args){state.args=args;return this;},async first(){return db.prepare(sql).get(...state.args);},async run(){return db.prepare(sql).run(...state.args);}};}};
const env={DASHSCOPE_API_KEY:'test-provider',AI_ACCESS_TOKEN:'012345',AI_DB:binding};
const now=new Date('2026-10-23T01:00:00Z');
const origin='https://test.pages.dev';
const request=(body=null,cookie='',options={})=>new Request(origin+(options.model?'/api/ai':'/api/ai-session'),{
  method:body?'POST':'GET',headers:{'Content-Type':'application/json',Origin:origin,...(cookie?{Cookie:cookie}:{}),...options.headers},...(body?{body:JSON.stringify(body)}:{})});
const session=(body,cookie='',time=now,override={})=>handleSession(request(body,cookie),{...env,...override},{now:time});
const unlock=remember=>session({action:'unlock',token:'012345',remember});
const cookieOf=response=>response.headers.get('Set-Cookie').split(';')[0];
assert.equal((await (await session(null)).json()).authenticated,false);
const remembered=await unlock(true), cookieA=cookieOf(remembered);
assert.equal(remembered.status,200);assert.match(cookieA,new RegExp('^'+SESSION_COOKIE+'=[a-f0-9]{64}$'));
const flags=remembered.headers.get('Set-Cookie');
for(const flag of ['Path=/','Secure','HttpOnly','SameSite=Strict','Max-Age=2592000'])assert.ok(flags.includes(flag));
assert.equal(Date.parse((await remembered.json()).expiresAt),+now+REMEMBER_MS);
const temporary=await unlock(false),cookieB=cookieOf(temporary);
assert.notEqual(cookieA,cookieB);assert.doesNotMatch(temporary.headers.get('Set-Cookie'),/Max-Age|Expires=/);
assert.equal(Date.parse((await temporary.json()).expiresAt),+now+SESSION_MS);
let rows=db.prepare('SELECT * FROM ai_sessions').all();
assert.equal(rows.length,2);
assert.ok(rows.every(row=>!cookieA.includes(row.token_hash)&&!JSON.stringify(row).includes('012345')),'only random credential hashes are stored');
assert.equal((await (await session(null,cookieA)).json()).remembered,true);
assert.equal((await (await session(null,cookieB,new Date(+now+SESSION_MS-1))).json()).authenticated,true);
const expired=await session(null,cookieB,new Date(+now+SESSION_MS));
assert.equal((await expired.json()).authenticated,false);assert.match(expired.headers.get('Set-Cookie'),/Max-Age=0/);
assert.equal((await (await session(null,cookieA,now,{AI_ACCESS_TOKEN:'654321'})).json()).authenticated,false,'rotating PIN invalidates old devices');
assert.equal((await (await session(null,cookieA,now,{DASHSCOPE_API_KEY:'other-test-provider'})).json()).authenticated,false);
assert.equal((await (await session(null,cookieA+'; '+cookieA)).json()).authenticated,false,'duplicate cookies cannot ambiguously authorize');
for(const action of ['unlock','logout','logoutAll']) {
  const body={action,token:'012345',remember:true};
  const missing=request(body,cookieA);missing.headers.delete('Origin');
  assert.equal((await handleSession(missing,env,{now})).status,403);
  assert.equal((await handleSession(request(body,cookieA,{headers:{Origin:'https://elsewhere.test'}}),env,{now})).status,403);
}
let providerCalls=0;
const fetcher=async()=>{providerCalls++;return Response.json({choices:[{finish_reason:'stop',message:{content:'{"ok":true}'}}]});};
const model=(cookie,headers={})=>handleAI(request({action:'probe'},cookie,{model:true,headers}),env,{now,fetcher});
assert.equal((await model(cookieA)).status,200);
assert.equal((await model('',{Authorization:'Bearer 012345'})).status,200);
assert.equal((await model(cookieB)).status,429,'all devices and legacy Bearer share the same owner quota');
assert.equal(providerCalls,2);
assert.equal((await model(cookieA,{Origin:''})).status,403,'cookie model calls require a same-origin browser request');
assert.equal((await session({action:'logout'},cookieA)).status,200);
assert.equal((await (await session(null,cookieA)).json()).authenticated,false);
assert.equal((await (await session(null,cookieB)).json()).authenticated,true,'current logout preserves another device');
const third=await unlock(true),cookieC=cookieOf(third);
assert.equal((await session({action:'logoutAll'},cookieB)).status,200);
assert.equal((await (await session(null,cookieC)).json()).authenticated,false);
assert.equal((await (await session(null,cookieB)).json()).authenticated,false);
const bad={prepare(){throw Error('offline');}};
assert.equal((await session({action:'unlock',token:'012345',remember:true},'',now,{AI_DB:bad})).status,503);
assert.equal((await session(null,cookieC,now,{AI_DB:bad})).status,503);
assert.equal(providerCalls,2,'status, login and logout never call a provider');
for(let i=0;i<5;i++)assert.equal((await session({action:'unlock',token:'999999',remember:true})).status,401);
assert.equal((await unlock(true)).status,429,'session login retains existing PIN attempt limits');
assert.equal((await session({action:'unlock',token:'012345',remember:true},'',new Date(+now+15*60000))).status,200);
console.log('Device sessions: cookie flags, random hashed credentials, 8h/30d expiry, restore, rotation, shared quota, CSRF, revocation and fail-closed PIN limits passed.');
