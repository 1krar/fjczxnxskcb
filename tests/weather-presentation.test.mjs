import assert from 'node:assert/strict';
import { weatherHeadline } from '../js/weather-presentation.js';
import { normalizeWeather,DEFAULT_WEATHER_LOCATION } from '../js/weather-model.js';
import { rawForecast } from './weather-fixture.mjs';
const now=new Date('2026-10-23T12:30:00+08:00');
const raw=rawForecast('2026-10-23');
raw.hourly.precipitation_probability=raw.hourly.time.map(time=>time.startsWith('2026-10-23')&&['14:00','15:00'].includes(time.slice(11))?60:0);
let weather=normalizeWeather(raw,DEFAULT_WEATHER_LOCATION,now),view=weatherHeadline(weather,now);
assert.equal(view.label,'今日日间预报');assert.equal(view.range,'21—21°C');assert.match(view.rain,/14:00—16:00.*60%/);
assert.doesNotMatch(view.rain,/一定|必然|预警/);
view=weatherHeadline(weather,new Date(+now+3600000));
assert.equal(view.label,'今日日间旧预报');assert.equal(view.rain,'','old forecasts do not generate a new rain hint');
assert.equal(weatherHeadline(weather,new Date(+now+7*3600000)).range,'','expired temperatures are not displayed as current');
assert.equal(weatherHeadline(null,now).label,'天气未更新');
weather={...weather,fetchedAt:'2026-10-23T16:30:00+08:00'};
assert.equal(weatherHeadline(weather,new Date('2026-10-23T16:30:00+08:00')).rain,'','past rain hours never look like an upcoming event');
const missing=structuredClone(weather);missing.hours.forEach(row=>row.rainProbability=null);
assert.equal(weatherHeadline(missing,new Date('2026-10-23T16:30:00+08:00')).rain,'');
console.log('Weather hierarchy: forecast labels, actual upcoming rain intervals, stale/expired data and missing probabilities passed.');
